import { readFileSync, writeFileSync } from 'node:fs';

export interface ErrorCodeEntry {
  code: string;
  status: number;
}

/** Every `x-error-codes` entry in the spec, the shared ones under `components.responses` included, once and sorted. */
export function errorCodes(spec: unknown): ErrorCodeEntry[] {
  const codes = new Map<string, number>();
  walk(spec, codes);

  return [...codes.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([code, status]) => ({ code, status }));
}

/** The TypeScript module the thin layer imports as `src/generated/error-codes.gen.ts`. */
export function render(codes: ErrorCodeEntry[]): string {
  const members = codes.map(({ code }) => `  ${member(code)}: '${code}',`).join('\n');
  const statuses = codes.map(({ code, status }) => `  ${code}: ${status},`).join('\n');

  return `// This file is generated by tools/codegen.ts from the x-error-codes of spec/api.json. Do not edit.

export const ErrorCode = {
${members}
} as const;

export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode];

export const errorCodeStatus: Record<ErrorCode, number> = {
${statuses}
};

export function isErrorCode(value: string): value is ErrorCode {
  return Object.hasOwn(errorCodeStatus, value);
}
`;
}

function walk(node: unknown, codes: Map<string, number>): void {
  if (Array.isArray(node)) {
    node.forEach((item) => walk(item, codes));
    return;
  }

  if (node === null || typeof node !== 'object') {
    return;
  }

  for (const [key, value] of Object.entries(node)) {
    if (key === 'x-error-codes' && Array.isArray(value)) {
      value.forEach((entry: { code: string; status: number }) => add(codes, entry.code, entry.status));
    } else {
      walk(value, codes);
    }
  }
}

function add(codes: Map<string, number>, code: string, status: number): void {
  const known = codes.get(code);
  if (known !== undefined && known !== status) {
    throw new Error(`${code} has two statuses: ${known} and ${status}.`);
  }

  codes.set(code, status);
}

function member(code: string): string {
  return code
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const spec = JSON.parse(readFileSync('spec/api.json', 'utf8'));
  writeFileSync('src/generated/error-codes.gen.ts', render(errorCodes(spec)));
}
